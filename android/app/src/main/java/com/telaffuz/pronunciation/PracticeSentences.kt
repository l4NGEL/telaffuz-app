fun randomPracticeSentence(exclude: String? = null): String {
    if (PRACTICE_SENTENCES.size <= 1) return PRACTICE_SENTENCES.first()
    var pick = PRACTICE_SENTENCES.random()
    while (pick == exclude) {
        pick = PRACTICE_SENTENCES.random()
    }
    return pick
}
